// Rebuilds the WillDev seal as pure vector outlines.
//   npm run logo
// Writes src/brand/logo-paths.ts (used by <Logo/>) and assets/brand/willdev-logo.svg.
// "W" and "WillDev" are set in Lexend Bold (OFL) and converted to paths, so the
// logo never depends on a font being installed. Geometry mirrors assets/brand/willianpfp.png
// mapped to a 1000 × 1000 box centred on (500, 500).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const font = opentype.loadSync(path.join(ROOT, 'node_modules/@fontsource/lexend/files/lexend-latin-700-normal.woff'));

/** Lays a string out as one path and fits it into a box (uniform scale by width, or stretched). */
function fit(text, size, box, { stretchX = false } = {}) {
  const p = font.getPath(text, 0, 0, size);
  const bb = p.getBoundingBox();
  const sy = box.h ? box.h / (bb.y2 - bb.y1) : box.w / (bb.x2 - bb.x1);
  const sx = stretchX ? box.w / (bb.x2 - bb.x1) : sy;
  const w = (bb.x2 - bb.x1) * sx;
  const x0 = box.cx - w / 2;
  const y0 = box.top;
  const t = (x, y) => [(x - bb.x1) * sx + x0, (y - bb.y1) * sy + y0];
  let d = '';
  for (const c of p.commands) {
    if (c.type === 'M' || c.type === 'L') {
      const [x, y] = t(c.x, c.y);
      d += `${c.type}${x.toFixed(2)} ${y.toFixed(2)}`;
    } else if (c.type === 'Q') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x, y] = t(c.x, c.y);
      d += `Q${x1.toFixed(2)} ${y1.toFixed(2)} ${x.toFixed(2)} ${y.toFixed(2)}`;
    } else if (c.type === 'C') {
      const [x1, y1] = t(c.x1, c.y1);
      const [x2, y2] = t(c.x2, c.y2);
      const [x, y] = t(c.x, c.y);
      d += `C${x1.toFixed(2)} ${y1.toFixed(2)} ${x2.toFixed(2)} ${y2.toFixed(2)} ${x.toFixed(2)} ${y.toFixed(2)}`;
    } else if (c.type === 'Z') d += 'Z';
  }
  return d;
}

// Measured on the 1307 × 1296 reference (centre ≈ 653, 650), scaled by 0.77.
const geometry = {
  disc: 410,
  ringOuter: 385,
  ringInner: 352,
  arcRadius: 368.5,
  w: fit('W', 400, { cx: 497, top: 285, w: 462, h: 308 }, { stretchX: true }),
  word: fit('WillDev', 120, { cx: 497, top: 628, w: 377 }),
  underline: { x1: 296, x2: 697, y: 745, pinkX1: 431, pinkX2: 566 },
};

const out = `// Generated by scripts/build-logo.mjs — do not edit by hand.
export const logoPaths = ${JSON.stringify(geometry, null, 2)} as const;
`;
fs.mkdirSync(path.join(ROOT, 'src/brand'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src/brand/logo-paths.ts'), out);

const { brand } = await import(path.join(ROOT, 'config/branding.ts'));
const c = brand.colors;
const a = (brand.logo.arcSweep * Math.PI) / 180;
const r = geometry.arcRadius;
const ex = 500 + r * Math.sin(a);
const ey = 500 - r * Math.cos(a);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" width="1000" height="1000">
  <title>${brand.name}</title>
  <circle cx="500" cy="500" r="${geometry.disc}" fill="${c.black}"/>
  <circle cx="500" cy="500" r="${geometry.ringOuter}" fill="none" stroke="${c.gray}" stroke-width="3"/>
  <circle cx="500" cy="500" r="${geometry.ringInner}" fill="none" stroke="${c.gray}" stroke-width="3"/>
  <path d="M500 ${500 - r} A${r} ${r} 0 0 1 ${ex.toFixed(2)} ${ey.toFixed(2)}" fill="none" stroke="${c.pink}" stroke-width="12" stroke-linecap="butt"/>
  <path d="${geometry.w}" fill="${c.lime}"/>
  <path d="${geometry.word}" fill="${c.lime}"/>
  <line x1="${geometry.underline.x1}" y1="${geometry.underline.y}" x2="${geometry.underline.x2}" y2="${geometry.underline.y}" stroke="${c.gray}" stroke-width="3"/>
  <line x1="${geometry.underline.pinkX1}" y1="${geometry.underline.y}" x2="${geometry.underline.pinkX2}" y2="${geometry.underline.y}" stroke="${c.pink}" stroke-width="5"/>
</svg>
`;
fs.writeFileSync(path.join(ROOT, 'assets/brand/willdev-logo.svg'), svg);
console.log('logo: src/brand/logo-paths.ts, assets/brand/willdev-logo.svg');
