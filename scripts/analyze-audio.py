"""Beat analysis for the soundtrack.

    python3 scripts/analyze-audio.py "assets/audio/<file>" [--start SECONDS]

Detects tempo and beat grid with librosa, finds where the kick drum is present,
chooses a 35 s window (the beat must enter early: the window starts half a
second before the first strong downbeat unless --start is given) and writes
config/track.ts. config/timing.ts derives every cut from that file, so a new
track only needs this script to run again.

Requires: pip install librosa soundfile (and ffmpeg on PATH for .m4a/.mp3).
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

import librosa
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DURATION = 35.0
PRE_ROLL = 0.5


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("audio")
    ap.add_argument("--start", type=float, default=None, help="force the window start (seconds)")
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        wav = os.path.join(tmp, "track.wav")
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", args.audio, "-ac", "1", "-ar", "22050", wav], check=True)
        y, sr = librosa.load(wav, sr=22050)

    total = len(y) / sr
    tempo, beats = librosa.beat.beat_track(y=y, sr=sr, units="time")
    tempo = float(np.atleast_1d(tempo)[0])

    # Kick strength at every beat: low-band energy right on the beat.
    hop = 256
    spec = np.abs(librosa.stft(y, n_fft=2048, hop_length=hop))
    freqs = librosa.fft_frequencies(sr=sr, n_fft=2048)
    low = spec[freqs < 150].sum(0)
    times = librosa.frames_to_time(np.arange(spec.shape[1]), sr=sr, hop_length=hop)

    def kick_at(t):
        i = np.searchsorted(times, t)
        return float(low[max(0, i - 2): i + 3].max())

    kicks = np.array([kick_at(b) for b in beats])
    kicks = kicks / kicks.max()

    if args.start is not None:
        start = args.start
    else:
        strong = [b for b, k in zip(beats, kicks) if k > 0.6]
        first = strong[0] if strong else beats[0]
        start = max(0.0, first - PRE_ROLL)
    start = round(start, 3)

    window = [(round(float(b), 3), round(float(k), 2)) for b, k in zip(beats, kicks) if start - 0.01 <= b <= start + DURATION + 0.01]
    data = {
        "file": os.path.basename(args.audio),
        "durationSeconds": round(total, 3),
        "bpm": round(tempo, 2),
        "windowStart": start,
        "beats": [b for b, _ in window],
        "kick": [k for _, k in window],
    }
    out = os.path.join(ROOT, "config", "track.ts")
    with open(out, "w") as f:
        f.write("// Generated by scripts/analyze-audio.py — do not edit by hand.\n")
        f.write("// beats: absolute times (s) in the source file, inside the chosen 35 s window.\n")
        f.write("// kick: relative low-band energy on each beat (0–1); low values mark breaks.\n")
        f.write("export const track = " + json.dumps(data, indent=2) + " as const;\n")
    print(f"tempo {tempo:.2f} BPM, window {start:.3f}–{start + DURATION:.3f} s, {len(window)} beats -> config/track.ts")


if __name__ == "__main__":
    sys.exit(main())
